def normalize_locale(locale: str | None) -> str:
    if not locale:
        return DEFAULT_LOCALE
    short = locale.split("-")[0].split("_")[0].lower()
    return short if short in SUPPORTED_LOCALES else DEFAULT_LOCALE


def language_name(locale: str) -> str:
    return LANGUAGE_NAMES.get(normalize_locale(locale), LANGUAGE_NAMES[DEFAULT_LOCALE])


def tr(locale: str | None, key: str, **kwargs) -> str:
    resolved = normalize_locale(locale)
    template = TRANSLATIONS.get(resolved, TRANSLATIONS[DEFAULT_LOCALE]).get(
        key,
        TRANSLATIONS[DEFAULT_LOCALE].get(key, key),
    )
    return template.format(**kwargs)
